# 1 Вариант
def recurse(n: int, s: int) -> None:
    """
    Выводит сумму последовательности чисел от n до 0, прибавленную к s.
    
    Параметры:
        n (int): Начальное целое число (должно быть >= 0).
        s (int): Аккумулятор суммы.
        
    """
    if n < 0:
        print("Параметр 'n' должен быть неотрицательным во избежание бесконечной рекурсии.")
    
    if n == 0:
        print(s)
    else:
        recurse(n - 1, n + s)

# 2 Вариант
def recurse_iterative(n: int, s: int) -> None:
    """
    Вычисляет сумму чисел от n до 0 и прибавляет к s, используя цикл.
    Безопасно при n < 0 (цикл просто не выполнится).
    """
    while n > 0:
        s += n
        n -= 1
    print(s)


